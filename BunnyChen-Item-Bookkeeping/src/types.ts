// ── 核心数据类型 ──────────────────────────────────────────

export interface OrderItem {
  id: number;
  order_id: string;
  parent_order_id: string;
  product_id: string;
  platform: string;
  store_name: string;
  product_name: string;
  model_style: string;
  quantity: number;
  total_price: number;
  order_time: string;
  daily_avg_cost: number;
  emoji: string;
  import_batch: string;
  product_url: string;
  /** 使用截止日期（空=仍在使用），格式 YYYY-MM-DD HH:mm:ss */
  end_date: string;
  /** 截止原因：""=使用中, "sold"=已售出, "scrapped"=已报废 */
  end_reason: string;
  /** 售出回收金额（仅 end_reason="sold" 时有意义） */
  sell_price: number;
  /** 归档标记：0=正常 1=已归档 */
  archived: boolean;
  /** 商品分类（匹配自动填充，用户可在编辑中修改） */
  category: string;
}

/** 微信收入/回款记录（AA 转账回款、退款、红包等）——独立于物品表，不参与资产/消费分析 */
export interface IncomeRecord {
  id: number;
  order_id: string;
  platform: string;
  peer: string;
  /** 微信交易类型（转账/退款/红包/二维码收款/群收款/亲属卡等） */
  income_type: string;
  amount: number;
  order_time: string;
  status: string;
  import_batch: string;
}

/** 微信收支总览（支出/回款/净支出） */
export interface WechatOverview {
  expense_total: number;
  income_total: number;
  net_total: number;
}

/** 微信收入按交易类型分组（退款/转账/红包/收款等） */
export interface IncomeByType {
  income_type: string;
  total: number;
  count: number;
}

/** 微信收入按交易对方分组（回款来源 Top） */
export interface IncomePeer {
  peer: string;
  total: number;
  count: number;
}

/** 微信月度收支（支出/回款/净支出） */
export interface WechatMonthly {
  month: string;
  expense: number;
  income: number;
  net: number;
}

/** 微信收支分析（分析页「微信收支」区块） */
export interface WechatAnalytics {
  overview: WechatOverview;
  by_type: IncomeByType[];
  peers: IncomePeer[];
  monthly: WechatMonthly[];
}

